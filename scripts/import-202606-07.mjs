const seen = new Set(existing.map(c => `${c.date}|${String(c.room).trim()}|${c.guest_comment}`))

let ins = 0, skip = 0
for (const [date, src, room, category, nature, guest_comment, improvement, actual_cause] of ROWS) {
  if (seen.has(`${date}|${room}|${guest_comment}`)) { skip++; continue }
  const row = {
    date, room, category, nature, guest_comment,
    actual_cause: actual_cause || '', correct_standard: '', improvement: improvement || '',
    shared: false, check_scheduled: false, recurred: false, photos: [],
  }
  if (hasSource) row.source = S[src]
  await req('POST', 'complaints', row)
  ins++
}
