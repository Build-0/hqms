create or replace function _sync_product_stock(p_product_id int) returns void
language plpgsql security definer set search_path = public, extensions
as $$
begin
  update products
     set stock = coalesce((select sum(qty_remaining) from product_batches where product_id = p_product_id), 0)
   where id = p_product_id;
end $$;

create or replace function receive_batch(p_password text, p_product_id int, p_qty int, p_expiry date, p_received date, p_note text)
returns products
language plpgsql security definer set search_path = public, extensions
as $$
declare prod products;
begin
  perform _require_admin(p_password);
  if p_qty is null or p_qty <= 0 then raise exception 'qty must be positive'; end if;
  insert into product_batches (product_id, received_date, expiry_date, qty_received, qty_remaining, note)
  values (p_product_id, coalesce(p_received, current_date), p_expiry, p_qty, p_qty, p_note);
  insert into stock_movements (product_id, kind, qty, happened_on, note)
  values (p_product_id, 'in', p_qty, coalesce(p_received, current_date), p_note);
  perform _sync_product_stock(p_product_id);
  select * into prod from products where id = p_product_id;
  return prod;
end $$;

create or replace function stock_count(p_password text, p_product_id int, p_actual int, p_date date, p_note text)
returns products
language plpgsql security definer set search_path = public, extensions
as $$
declare
  prod products;
  cur int;
  diff int;
  need int;
  take int;
  addq int;
  latest int;
  b record;
  cdate date := coalesce(p_date, current_date);
begin
  perform _require_admin(p_password);
  if p_actual is null or p_actual < 0 then raise exception 'invalid count'; end if;
  select coalesce(sum(qty_remaining), 0) into cur from product_batches where product_id = p_product_id;
  diff := cur - p_actual;                       -- 正 = 用掉

  if diff > 0 then
    need := diff;
    for b in select id, qty_remaining from product_batches
             where product_id = p_product_id and qty_remaining > 0
             order by expiry_date asc nulls last, received_date asc, id asc
    loop
      exit when need <= 0;
      take := least(need, b.qty_remaining);
      update product_batches set qty_remaining = qty_remaining - take where id = b.id;
      need := need - take;
    end loop;
    insert into stock_movements (product_id, kind, qty, happened_on, note)
    values (p_product_id, 'out', diff, cdate, coalesce(p_note, '盤點'));

  elsif diff < 0 then
    addq := -diff;                              -- 實數 > 帳面：正向調整
    select id into latest from product_batches
      where product_id = p_product_id
      order by received_date desc nulls last, id desc limit 1;
    if latest is null then
      insert into product_batches (product_id, received_date, expiry_date, qty_received, qty_remaining, note)
      values (p_product_id, cdate, null, addq, addq, '盤點調整');
    else
      update product_batches set qty_remaining = qty_remaining + addq where id = latest;
    end if;
    insert into stock_movements (product_id, kind, qty, happened_on, note)
    values (p_product_id, 'adjust', addq, cdate, coalesce(p_note, '盤點調整(增加)'));
  end if;

  perform _sync_product_stock(p_product_id);
  select * into prod from products where id = p_product_id;
  return prod;
end $$;

create or replace function update_batch(p_password text, p_batch_id int, p_qty_remaining int, p_expiry date, p_received date, p_note text)
returns products
language plpgsql security definer set search_path = public, extensions
as $$
declare prod products; pid int;
begin
  perform _require_admin(p_password);
  select product_id into pid from product_batches where id = p_batch_id;
  if not found then raise exception 'batch not found'; end if;
  update product_batches set
    qty_remaining = coalesce(p_qty_remaining, qty_remaining),
    expiry_date   = p_expiry,
    received_date = coalesce(p_received, received_date),
    note          = p_note
  where id = p_batch_id;
  perform _sync_product_stock(pid);
  select * into prod from products where id = pid;
  return prod;
end $$;

create or replace function delete_batch(p_password text, p_batch_id int)
returns products
language plpgsql security definer set search_path = public, extensions
as $$
declare prod products; pid int; q int;
begin
  perform _require_admin(p_password);
  select product_id, qty_remaining into pid, q from product_batches where id = p_batch_id;
  if not found then raise exception 'batch not found'; end if;
  if q > 0 then
    insert into stock_movements (product_id, kind, qty, happened_on, note)
    values (pid, 'dispose', q, current_date, '刪除批次');
  end if;
  delete from product_batches where id = p_batch_id;
  perform _sync_product_stock(pid);
  select * into prod from products where id = pid;
  return prod;
end $$;

