-- ── 搬資料後用：把各表序號對齊到目前最大 id ──
create or replace function merge_fix_sequences() returns void language plpgsql security definer as $$
declare t text; q text;
begin
  foreach t in array array['boh_categories','products','vacuums','vacuum_maintenance','tools','equipment','equipment_maintenance','product_batches','stock_movements','tool_categories','equipment_types','vacuum_floors','defect_types','defect_records'] loop
    q := pg_get_serial_sequence('public.' || t, 'id');
    if q is not null then execute format('select setval(%L, coalesce((select max(id) from %I), 0) + 1, false)', q, t); end if;
  end loop;
end $$;
